"""Fused C11 lowering and the synchronous native-build/runtime owner.

Native code is trusted generated code, not a sandbox. Raw ctypes integration
attributes are for trusted benchmarks. Concurrent close/use is unsupported.
"""

import ctypes
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .interpreter import validate_columns
from .ir import MairgError, Program, checked_program
from .optimizer import Plan, optimize

U64 = ctypes.c_uint64
U64Pointer = ctypes.POINTER(U64)
ColumnPointers = ctypes.POINTER(U64Pointer)

_BINARY = {
    "add": "+", "sub": "-", "mul": "*", "bit_and": "&", "bit_or": "|",
    "bit_xor": "^", "eq": "==", "lt": "<", "le": "<=", "gt": ">",
    "ge": ">=", "and": "&", "or": "|",
}


def _emit_checked(program: Program) -> str:
    lines = [
        "/* Generated by MAIRG. External names are not source-code identifiers. */",
        "#include <stdint.h>", "#include <stddef.h>",
        "void mairg_kernel(size_t n, const uint64_t *const *cols, uint64_t *out) {",
    ]
    for index in range(len(program.outputs)):
        lines.append(f"  uint64_t a_{index} = UINT64_C(0);")
    lines.append("  for (size_t row = 0; row < n; ++row) {")
    for node in program.nodes:
        args = node.args
        if node.op == "input":
            expression = f"cols[{args[0]}][row]"
        elif node.op == "u64":
            expression = f"UINT64_C({args[0]})"
        elif node.op == "bool":
            expression = f"UINT64_C({1 if args[0] else 0})"
        elif node.op in _BINARY:
            expression = f"(v_{args[0]} {_BINARY[node.op]} v_{args[1]})"
        elif node.op == "not":
            expression = f"(!v_{args[0]})"
        elif node.op == "select":
            expression = f"(v_{args[0]} ? v_{args[1]} : v_{args[2]})"
        else:
            raise MairgError("internal_op", "validated operation has no native emitter", "nodes")
        lines.append(f"    const uint64_t v_{node.id} = {expression};")
    # Predicates are exactly 0/1. Unsigned subtraction yields an all-zero/all-one
    # mask, preserving every reduction's zero identity without control flow.
    predicates = sorted({output.where for output in program.outputs if output.value is not None})
    for predicate in predicates:
        lines.append(f"    const uint64_t mask_{predicate} = UINT64_C(0) - v_{predicate};")
    for index, output in enumerate(program.outputs):
        if output.op == "count":
            lines.append(f"    a_{index} += v_{output.where};")
        else:
            lines.append(f"    const uint64_t selected_{index} = v_{output.value} & mask_{output.where};")
            if output.op == "sum":
                lines.append(f"    a_{index} += selected_{index};")
            elif output.op == "xor":
                lines.append(f"    a_{index} ^= selected_{index};")
            elif output.op == "max":
                lines.append(f"    if (selected_{index} > a_{index}) a_{index} = selected_{index};")
            else:
                raise MairgError("internal_op", "validated reduction has no native emitter", "outputs")
    lines.append("  }")
    for index in range(len(program.outputs)):
        lines.append(f"  out[{index}] = a_{index};")
    lines.extend(["}", ""])
    return "\n".join(lines)


def emit_c(program: Program) -> str:
    """Lower a checked graph. Compilation separately controls optimization."""
    return _emit_checked(checked_program(program))


@dataclass(frozen=True)
class PreparedBatch:
    """Pinned positional buffers. Raw pointers belong to trusted integration."""

    schema: tuple[tuple[str, str], ...]
    n: int
    buffers: tuple[Any, ...]
    pointers: Any


def prepare_batch(program: Program, columns: Any) -> PreparedBatch:
    """Prepare the same checked positional buffers for generated/traditional kernels."""
    program = checked_program(program)
    values, count = validate_columns(program, columns)
    buffers = tuple((U64 * count)(*(int(value) for value in column)) for column in values)
    pointers = (U64Pointer * len(buffers))(*(ctypes.cast(buffer, U64Pointer) for buffer in buffers))
    return PreparedBatch(program.inputs, count, buffers, pointers)


class CompiledProgram:
    """Own one private build and library; use synchronously as a context manager."""

    def __init__(
        self, plan: Plan, source: str, directory: tempfile.TemporaryDirectory[str],
        library: Any, library_path: Path, command: list[str], build_seconds: float,
    ) -> None:
        self.plan = plan
        self.source = source
        self._temporary: tempfile.TemporaryDirectory[str] | None = directory
        self.directory = Path(directory.name)
        self.library_path = library_path
        self.compiler_command = tuple(command)
        self.build_seconds = build_seconds
        self._library = library
        self._closed = False
        self.kernel = library.mairg_kernel
        self.kernel.argtypes = [ctypes.c_size_t, ColumnPointers, U64Pointer]
        self.kernel.restype = None

    def _require_open(self) -> None:
        if self._closed:
            raise MairgError("closed", "compiled program is closed", "runtime")

    def prepare(self, columns: Any) -> PreparedBatch:
        self._require_open()
        return prepare_batch(self.plan.program, columns)

    def run(self, columns: Any) -> dict[str, int]:
        return self.run_prepared(self.prepare(columns))

    def run_prepared(self, batch: PreparedBatch) -> dict[str, int]:
        self._require_open()
        if not isinstance(batch, PreparedBatch) or batch.schema != self.plan.program.inputs:
            raise MairgError("input_schema", "prepared batch has a different input schema", "batch")
        output = (U64 * len(self.plan.program.outputs))()
        self.kernel(batch.n, batch.pointers, output)
        return {item.name: int(output[index]) for index, item in enumerate(self.plan.program.outputs)}

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        self.kernel = None
        self._library = None
        temporary = self._temporary
        self._temporary = None
        if temporary is not None:
            temporary.cleanup()

    def __enter__(self) -> "CompiledProgram":
        self._require_open()
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()


def _stop_compiler(process: subprocess.Popen[str]) -> None:
    """Stop the owned process group and reap its direct driver, bounded to 4s."""
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    try:
        process.communicate(timeout=2)
    except subprocess.TimeoutExpired:
        pass
    # A driver may have exited while a descendant ignores TERM or closes pipes.
    try:
        os.killpg(process.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        process.communicate(timeout=2)
    except subprocess.TimeoutExpired as error:
        raise MairgError("compiler_cleanup", "compiler driver could not be reaped", "compiler") from error


def _compiler_path(compiler: str | os.PathLike[str] | None) -> str:
    if compiler is None:
        selected = shutil.which("clang") or shutil.which("gcc")
    else:
        selected = shutil.which(os.fspath(compiler))
    if selected is None:
        raise MairgError("compiler_missing", "a Clang or GCC executable is required", "compiler")
    return selected


def compile_program(
    program: Program, optimize_enabled: bool = True, *,
    compiler: str | os.PathLike[str] | None = None, timeout: float = 60,
) -> CompiledProgram:
    """Compile into a fresh private directory; failures never publish an artifact."""
    program = checked_program(program)
    if type(optimize_enabled) is not bool:
        raise MairgError("compiler_option", "optimize_enabled must be bool", "compiler")
    if type(timeout) not in (int, float) or not 0 < timeout <= 60:
        raise MairgError("compiler_option", "timeout must be positive and at most 60 seconds", "compiler")
    if sys.platform not in ("darwin", "linux"):
        raise MairgError("platform", "native compilation supports macOS and Linux", "compiler")
    executable = _compiler_path(compiler)
    canonical = optimize(program)
    if optimize_enabled:
        plan = canonical
    else:
        # The semantic fingerprint remains that of the canonical optimized graph.
        stats = dict(canonical.stats)
        stats.update({"optimized_nodes": len(program.nodes), "folded_nodes": 0,
                      "merged_nodes": 0, "dead_nodes": 0})
        plan = Plan(program, canonical.fingerprint, stats)
    source = _emit_checked(plan.program)
    temporary: tempfile.TemporaryDirectory[str] = tempfile.TemporaryDirectory(prefix="mairg-build-")
    process: subprocess.Popen[str] | None = None
    started = time.perf_counter()
    try:
        directory = Path(temporary.name)
        source_path = directory / "kernel.c"
        library_path = directory / ("kernel.dylib" if sys.platform == "darwin" else "kernel.so")
        source_path.write_text(source, encoding="ascii")
        platform_flag = "-dynamiclib" if sys.platform == "darwin" else "-shared"
        command = [executable, "-O3", "-std=c11", "-fPIC", platform_flag,
                   str(source_path), "-o", str(library_path)]
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                   text=True, start_new_session=True)
        try:
            _stdout, stderr = process.communicate(timeout=timeout)
        except subprocess.TimeoutExpired as error:
            raise MairgError("compiler_timeout", "native compiler timed out", "compiler") from error
        if process.returncode != 0:
            raise MairgError("compiler_failed", stderr[-4096:] or "native compiler failed", "compiler")
        try:
            library = ctypes.CDLL(str(library_path))
            result = CompiledProgram(plan, source, temporary, library, library_path,
                                     command, time.perf_counter() - started)
        except (OSError, AttributeError) as error:
            raise MairgError("library_load", "compiler output could not be loaded", "compiler") from error
        return result
    except BaseException as error:
        try:
            if process is not None:
                _stop_compiler(process)
        finally:
            temporary.cleanup()
        if isinstance(error, (MairgError, KeyboardInterrupt, SystemExit)):
            raise
        raise MairgError("compiler_io", str(error), "compiler") from error
